use crate::filesystem::has_marker_file;
use crate::model::Category;
use crate::scanner::Scanner;
use std::path::Path;

pub struct NodeModulesScanner;

impl Scanner for NodeModulesScanner {
    fn category(&self) -> Category {
        Category::NodeModules
    }

    /// `.angular` is the CLI's build cache and sits beside `node_modules` in
    /// the same project, so it is confirmed by the same `package.json`.
    fn matches(&self, name: &str) -> bool {
        name == "node_modules" || name == ".angular"
    }

    fn confirm_context(&self, path: &Path) -> bool {
        !is_nested_node_modules(path)
            && !is_tooling_node_modules(path)
            && path
                .parent()
                .is_some_and(|parent| has_marker_file(parent, "package.json"))
    }
}

fn is_nested_node_modules(path: &Path) -> bool {
    path.ancestors()
        .skip(1)
        .filter_map(Path::file_name)
        .any(|name| name.to_string_lossy().eq_ignore_ascii_case("node_modules"))
}

fn is_tooling_node_modules(path: &Path) -> bool {
    let parts = path
        .components()
        .map(|component| component.as_os_str().to_string_lossy().to_lowercase())
        .collect::<Vec<_>>();
    parts.windows(5).any(|window| {
        window
            == [
                "visualstudio",
                "msbuild",
                "microsoft",
                "visualstudio",
                "nodejs",
            ]
    }) || parts.windows(2).any(|window| {
        window[0] == "nvm"
            && window[1].starts_with('v')
            && window[1][1..]
                .chars()
                .all(|character| character.is_ascii_digit() || character == '.')
    })
}
