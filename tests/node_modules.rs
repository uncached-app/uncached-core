use std::fs;
use std::path::{Path, PathBuf};
use uncached_core::{
    clean_to_trash, scan_workspace, validate_clean_target, Category, CoreError, ProviderSet,
    ScanTarget,
};

fn fixture(name: &str) -> PathBuf {
    let root = std::env::temp_dir().join(format!(
        "uncached-core-{name}-{}-{}",
        std::process::id(),
        std::thread::current().name().unwrap_or("test")
    ));
    let _ = fs::remove_dir_all(&root);
    fs::create_dir_all(&root).unwrap();
    root
}

fn project(root: &Path, name: &str, bytes: &[u8]) -> PathBuf {
    let node_modules = root.join(name).join("node_modules");
    fs::create_dir_all(&node_modules).unwrap();
    fs::write(node_modules.join("package.bin"), bytes).unwrap();
    fs::write(root.join(name).join("package.json"), b"{}").unwrap();
    node_modules
}

fn cleanup(root: &Path) {
    let _ = fs::remove_dir_all(root);
}

#[test]
fn scans_top_level_and_nested_project_targets_with_byte_totals() {
    let root = fixture("valid");
    let first = project(&root, "alpha", b"123");
    let second = project(&root, "beta", b"12345");

    let report = scan_workspace(&root, &ProviderSet::free()).unwrap();

    assert_eq!(report.targets.len(), 2);
    assert_eq!(report.total_bytes, 8);
    assert_eq!(report.targets[0].path, fs::canonicalize(first).unwrap());
    assert_eq!(report.targets[1].path, fs::canonicalize(second).unwrap());
    assert!(report
        .targets
        .iter()
        .all(|target| target.category == Category::NodeModules));
    cleanup(&root);
}

#[test]
fn requires_regular_parent_package_json() {
    let root = fixture("context");
    let missing = root.join("missing").join("node_modules");
    fs::create_dir_all(&missing).unwrap();
    let package_dir = root.join("directory-package").join("node_modules");
    fs::create_dir_all(&package_dir).unwrap();
    fs::create_dir(root.join("directory-package").join("package.json")).unwrap();
    project(&root, "valid", b"x");

    let report = scan_workspace(&root, &ProviderSet::free()).unwrap();

    assert_eq!(report.targets.len(), 1);
    assert_eq!(report.targets[0].path.file_name().unwrap(), "node_modules");
    cleanup(&root);
}

#[test]
fn prunes_nested_targets_and_ignores_symlinked_files_and_directories() {
    let root = fixture("pruning");
    let target = project(&root, "app", b"real");
    let nested = target.join("dependency").join("node_modules");
    fs::create_dir_all(&nested).unwrap();
    fs::write(nested.join("nested.bin"), b"must not count").unwrap();

    #[cfg(unix)]
    std::os::unix::fs::symlink(root.join("app"), root.join("linked-project")).unwrap();
    #[cfg(windows)]
    if std::os::windows::fs::symlink_dir(root.join("app"), root.join("linked-project")).is_err() {
        cleanup(&root);
        return;
    }

    #[cfg(unix)]
    std::os::unix::fs::symlink(target.join("package.bin"), target.join("linked.bin")).unwrap();
    #[cfg(windows)]
    if std::os::windows::fs::symlink_file(target.join("package.bin"), target.join("linked.bin"))
        .is_err()
    {
        cleanup(&root);
        return;
    }

    let report = scan_workspace(&root, &ProviderSet::free()).unwrap();

    assert_eq!(report.targets.len(), 1);
    assert_eq!(report.total_bytes, 18);
    cleanup(&root);
}

