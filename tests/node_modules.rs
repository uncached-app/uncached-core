#[test]
fn parallel_bounded_sizing_keeps_target_output_deterministic() {
    let root = fixture("parallel-sizing");
    for index in (0..24).rev() {
        project(&root, &format!("project-{index:02}"), &[index as u8]);
    }

    // directory_size_report uses a bounded jwalk Rayon pool; scan sorts targets
    // after traversal so parallel completion order never affects the API.
    let cancelled = AtomicBool::new(false);
    let ScanOutcome::Completed(report) =
        scan_workspace(&root, &ProviderSet::free(), &cancelled).unwrap()
    else {
        panic!("scan unexpectedly cancelled");
    };
    let paths = report
        .targets
        .iter()
        .map(|target| target.path.clone())
        .collect::<Vec<_>>();
    let mut sorted = paths.clone();
    sorted.sort();
    assert_eq!(paths, sorted);
    cleanup(&root);
}

