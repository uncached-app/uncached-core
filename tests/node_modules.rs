#[test]
fn rejects_missing_file_and_symlink_workspaces() {
    let missing = fixture("missing").join("gone");
    let _ = fs::remove_dir_all(missing.parent().unwrap());
    assert!(matches!(
        scan_workspace(&missing, &ProviderSet::free()),
        Err(CoreError::InvalidWorkspace(_))
    ));

    let root = fixture("symlink-workspace");
    let real = fixture("symlink-workspace-real");
    #[cfg(unix)]
    std::os::unix::fs::symlink(&real, root.join("link")).unwrap();
    #[cfg(windows)]
    if std::os::windows::fs::symlink_dir(&real, root.join("link")).is_err() {
        cleanup(&root);
        cleanup(&real);
        return;
    }
    assert!(matches!(
        scan_workspace(&root.join("link"), &ProviderSet::free()),
        Err(CoreError::InvalidWorkspace(_))
    ));
    cleanup(&root);
    cleanup(&real);
}

#[test]
fn rejects_outside_and_tampered_targets_before_trash() {
    let root = fixture("validation");
    let target = project(&root, "app", b"x");
    let outside = fixture("outside");
    let outside_target = project(&outside, "other", b"x");
    let valid = ScanTarget::new(target.clone(), Category::NodeModules, 1);
    let outside_target = ScanTarget::new(outside_target, Category::NodeModules, 1);

    assert!(validate_clean_target(&root, &valid).is_ok());
    assert!(validate_clean_target(&root, &outside_target).is_err());
    assert!(clean_to_trash(&root, &outside_target).is_err());

    let wrong_name = ScanTarget::new(
        target.with_file_name("not-node-modules"),
        Category::NodeModules,
        1,
    );
    assert!(validate_clean_target(&root, &wrong_name).is_err());
    cleanup(&root);
    cleanup(&outside);
}

