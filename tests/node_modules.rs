#[test]
fn streaming_traversal_is_sorted_and_prunes_matched_targets() {
    let root = fixture("streaming");
    let first = project(&root, "a-project", b"a");
    let second = project(&root, "b-project", b"b");
    fs::create_dir_all(first.join("nested")).unwrap();

    let mut visited = Vec::new();
    let cancelled = AtomicBool::new(false);
    let outcome = traverse_workspace(&root, &ProviderSet::free(), &cancelled, |entry| {
        visited.push((entry.path.clone(), entry.category.clone()));
        if entry.category == Some(Category::NodeModules) {
            TraversalControl::Prune
        } else {
            TraversalControl::Continue
        }
    })
    .unwrap();

    assert_eq!(outcome, TraversalOutcome::Completed);

    assert_eq!(
        visited
            .iter()
            .filter_map(|(path, category)| category.as_ref().map(|_| path.clone()))
            .collect::<Vec<_>>(),
        vec![
            fs::canonicalize(first).unwrap(),
            fs::canonicalize(second).unwrap()
        ]
    );
    assert!(!visited.iter().any(|(path, _)| path.ends_with("nested")));
    cleanup(&root);
}

