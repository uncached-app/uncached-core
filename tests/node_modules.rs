fn fixture(name: &str) -> PathBuf {
    let root = std::env::temp_dir().join(format!(
        "uncached-core-{name}-{}-{}",
        std::process::id(),
        std::thread::current().name().unwrap_or("test")
    ));
    let _ = fs::remove_dir_all(&root);
    fs::create_dir_all(&root).unwrap();
    root
}

fn project(root: &Path, name: &str, bytes: &[u8]) -> PathBuf {
    let node_modules = root.join(name).join("node_modules");
    fs::create_dir_all(&node_modules).unwrap();
    fs::write(node_modules.join("package.bin"), bytes).unwrap();
    fs::write(root.join(name).join("package.json"), b"{}").unwrap();
    node_modules
}

fn cleanup(root: &Path) {
    let _ = fs::remove_dir_all(root);
}

fn cleanup_candidate(path: PathBuf, category: Category, size_bytes: u64) -> ScanTarget {
    let candidate = ScanTarget::new(path, category, size_bytes);
    let identity = uncached_core::filesystem::file_identity(&candidate.path);
    candidate.with_identity(identity)
}

struct CustomScanner;

impl Scanner for CustomScanner {
    fn category(&self) -> Category {
        Category::Custom("fixture".to_owned())
    }

    fn matches(&self, name: &str) -> bool {
        name == "custom-target"
    }

    fn confirm_context(&self, path: &Path) -> bool {
        path.parent()
            .and_then(|parent| fs::symlink_metadata(parent.join("custom.marker")).ok())
            .is_some_and(|metadata| metadata.is_file() && !metadata.file_type().is_symlink())
    }
}

