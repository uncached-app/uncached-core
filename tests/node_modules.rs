#[test]
fn rejects_symlinked_target_parent_before_trash() {
    let root = fixture("cleanup-symlink-parent");
    let real_project = project(&root, "real-project", b"must remain");
    let linked_project = root.join("linked-project");
    #[cfg(unix)]
    std::os::unix::fs::symlink(root.join("real-project"), &linked_project).unwrap();
    #[cfg(windows)]
    if std::os::windows::fs::symlink_dir(root.join("real-project"), &linked_project).is_err() {
        cleanup(&root);
        return;
    }

    let candidate = ScanTarget::new(
        linked_project.join("node_modules"),
        Category::NodeModules,
        1,
    );
    assert!(matches!(
        clean_to_trash(&root, &candidate),
        Err(CoreError::InvalidTarget(_))
    ));
    assert!(real_project.exists());
    assert!(real_project.join("package.bin").exists());
    cleanup(&root);
}

#[test]
fn maps_missing_or_invalid_cleanup_package_json_to_invalid_target() {
    let root = fixture("cleanup-package");
    let missing = root.join("missing").join("node_modules");
    fs::create_dir_all(&missing).unwrap();
    let invalid = root.join("invalid").join("node_modules");
    fs::create_dir_all(&invalid).unwrap();
    fs::create_dir(root.join("invalid").join("package.json")).unwrap();
    let symlinked = project(&root, "symlinked", b"x");
    let package_link = root.join("symlinked").join("package-link.json");
    #[cfg(unix)]
    std::os::unix::fs::symlink(root.join("symlinked").join("package.json"), &package_link).unwrap();
    #[cfg(windows)]
    if std::os::windows::fs::symlink_file(
        root.join("symlinked").join("package.json"),
        &package_link,
    )
    .is_err()
    {
        cleanup(&root);
        return;
    }
    fs::remove_file(root.join("symlinked").join("package.json")).unwrap();
    fs::rename(&package_link, root.join("symlinked").join("package.json")).unwrap();

    for path in [missing, invalid, symlinked] {
        let candidate = ScanTarget::new(path, Category::NodeModules, 1);
        assert!(matches!(
            validate_clean_target(&root, &candidate),
            Err(CoreError::InvalidTarget(_))
        ));
    }
    cleanup(&root);
}

