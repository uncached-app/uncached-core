#[test]
fn scans_all_configured_provider_categories() {
    let root = fixture("all-provider-categories");
    let node_modules = project(&root, "node-project", b"node");
    let custom_project = root.join("custom-project");
    let custom_target = custom_project.join("custom-target");
    fs::create_dir_all(custom_target.join("nested")).unwrap();
    fs::write(custom_project.join("custom.marker"), b"").unwrap();
    fs::write(custom_target.join("nested").join("ignored.bin"), b"ignored").unwrap();

    let mut providers = ProviderSet::with_scanner(NodeModulesScanner);
    providers.add_scanner(CustomScanner);
    let mut traversal_identities = Vec::new();
    traverse_workspace(&root, &providers, &AtomicBool::new(false), |entry| {
        if entry.category.is_some() {
            traversal_identities.push((entry.path.clone(), entry.identity));
            TraversalControl::Prune
        } else {
            assert!(
                entry.identity.is_none(),
                "non-candidate traversal entry must not carry identity: {}",
                entry.path.display()
            );
            TraversalControl::Continue
        }
    })
    .unwrap();
    traversal_identities.sort_by(|left, right| left.0.cmp(&right.0));
    let node_modules = fs::canonicalize(&node_modules).unwrap();
    let mut sized_paths = Vec::new();
    let cancelled = AtomicBool::new(false);
    let ScanOutcome::Completed(report) =
        scan_workspace_with_sizing(&root, &providers, &cancelled, |path| {
            sized_paths.push(path.to_owned());
            Ok(if path == node_modules { 11 } else { 22 })
        })
        .unwrap()
    else {
        panic!("scan unexpectedly cancelled");
    };

    let custom_target = fs::canonicalize(custom_target).unwrap();
    assert_eq!(
        report
            .targets
            .iter()
            .map(|target| target.path.clone())
            .collect::<Vec<_>>(),
        vec![custom_target.clone(), node_modules.clone()]
    );
    assert_eq!(
        report
            .targets
            .iter()
            .map(|target| target.category.clone())
            .collect::<Vec<_>>(),
        vec![
            Category::Custom("fixture".to_owned()),
            Category::NodeModules
        ]
    );
    assert_eq!(report.targets[0].size_bytes, 22);
    assert_eq!(report.targets[1].size_bytes, 11);
    assert_eq!(
        report
            .targets
            .iter()
            .map(|target| (target.path.clone(), target.identity))
            .collect::<Vec<_>>(),
        traversal_identities
    );
    assert_eq!(report.total_bytes, 33);
    assert_eq!(sized_paths, vec![custom_target, node_modules]);
    cleanup(&root);
}

